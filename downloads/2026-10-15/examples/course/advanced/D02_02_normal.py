#
# 구성요소와 기호
# 여러 매개변수: 쉼표로 받는 자리를 구분합니다. 자리 순서로 전달하면 함수 정의 순서와 맞아야 합니다.
# 기본값: rate=0.1은 생략했을 때 0.1을 사용한다는 뜻입니다. 기본값 없는 매개변수를 먼저 씁니다.
# 키워드 인수: rate=0.2처럼 이름을 지정해 전달하면 어떤 값인지 읽기 쉽습니다.
# 지역 변수: 함수 몸통에서 만든 계산용 이름은 그 호출 안에서 사용합니다. 다른 호출의 값을 기억하는 저장소가 아닙니다.
# docstring: 함수 첫 줄의 삼중 따옴표 설명은 입력과 반환값의 약속을 적는 문서입니다.
#
# 이 단원의 첫 예제 실행을 따라가기
# discounted_price(10000)은 price=10000, rate=0.1로 실행되어 9000을 반환합니다.
# rate=0.2를 지정하면 기본값 대신 0.2를 사용해 8000을 반환합니다.
#
# 한 부분 바꾸고 확인하기
# 두 번째 예제의 기본 할인율을 0.1에서 0.15로 바꾸세요. 기본값으로 호출한 결과만 바뀌고 rate=0.2 결과는
# 그대로인지 비교하세요.

def discounted_price(price, rate=0.1):
    """원 단위 정수 가격과 0~1 할인율을 받아 최종 가격을 반환합니다."""
    # 10%는 숫자 10이 아니라 0.1로 전달한다는 약속입니다.
    discount = price * rate
    # 지역 변수 discount는 이 함수 호출의 계산에 사용합니다.
    result = int(price - discount)
    # 이 예제는 최종 금액의 소수 부분을 버리는 약속을 사용합니다.
    return result

# 인수가 하나면 rate는 함수 정의의 기본값 0.1을 사용합니다.
print(f"기본 할인: {discounted_price(10000)}")
# 이름을 지정하면 입력의 의미를 읽기 쉽습니다.
print(f"지정 할인: {discounted_price(price=10000, rate=0.2)}")
print(f"할인 없음: {discounted_price(10000, rate=0)}")
