# 리스트 안 딕셔너리: records[0]["name"]은 첫 기록을 고른 다음 name 값을 읽습니다.
# 대입: working = original은 자료를 복사하지 않고 같은 자료에 이름을 하나 더 붙입니다.
# 얕은 복사: original.copy()는 바깥 통을 복사하지만 안에 든 리스트·딕셔너리는 함께 가리킬 수 있습니다.
# 깊은 복사: copy.deepcopy는 이 예제처럼 안쪽 자료까지 수정하는 작업본을 만들 때 사용합니다.
# 원본 확인: 작업본을 수정한 뒤 원본도 출력해 비교해야 보존 여부를 확인할 수 있습니다.
#
# 이 단원의 첫 예제 실행을 따라가기
# 원본의 첫 행에서 readings 목록을 꺼냅니다. 얕은 사본에서도 같은 안쪽 목록을 사용하므로 원본이 함께 바뀝니다.
# 깊은 사본에서는 안쪽 목록까지 별도로 만들어 원본이 유지됩니다.
#
# 한 부분 바꾸고 확인하기
# 두 번째 예제의 deepcopy(original)을 original.copy()로 바꾸고 실행하세요. 원본의 점수 목록까지
# 바뀌는지 비교한 뒤 깊은 복사로 복구하세요.

from copy import deepcopy

# 리스트는 여러 학생을, 딕셔너리는 한 학생의 항목을 나타냅니다.
original = [{"name": "민수", "scores": [70, 80]}]
# 안쪽 scores 목록까지 독립적인 작업본을 만듭니다.
working = deepcopy(original)
# [0]으로 첫 학생, ["scores"]로 그 학생의 점수 목록을 찾습니다.
working[0]["scores"].append(90)
# 원본과 작업본을 모두 확인해야 원본 보존을 확인할 수 있습니다.
print(f"원본: {original[0]['scores']}")
print(f"작업본: {working[0]['scores']}")
# 값을 추가하는 append는 목록을 변경합니다. 새 목록을 반환하지 않습니다.
