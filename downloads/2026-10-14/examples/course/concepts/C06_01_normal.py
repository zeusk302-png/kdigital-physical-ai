# ---------------------------------------------------------------------
# [구성요소]
# input(prompt): 안내 글자를 보여 주고 사용자가 Enter를 누를
# 때까지 기다립니다.
# int(text): 정수 형태의 문자열을 정수로 바꿉니다. "2.5"나
# "천원"은 정수로 변환되지 않습니다.
# float(text): 소수 입력을 숫자로 바꿉니다. 잘못된 입력 처리 방법은
# 예외 단원에서 배웁니다.
# 입력과 출력: 사용자가 입력한 글자와 프로그램의 출력은 구별합니다. 예상
# 출력에는 키보드 입력 자체를 생략합니다.
# [실행 과정]
# 첫 입력 3은 문자열 "3"입니다. int로 바꾼 다음 5와 더하면 8입니다.
# 글자끼리 연결하면 "35"입니다.
# [직접 확장할 문제]
# 단가와 수량을 각각 입력받아 금액을 출력하세요. 수량 0일 때 결과도 확인하세요.
# ---------------------------------------------------------------------
first = input("첫 수: ")
second = input("둘째 수: ")
# raw 입력은 둘 다 문자열입니다.
print("문자 연결:", first + second)
first_number = int(first)
second_number = int(second)
print("숫자 합:", first_number + second_number)
