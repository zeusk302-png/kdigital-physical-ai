# 무엇을 배우나요? print는 값을 화면에 보여 주는 함수입니다. 주석은 사람이
# 읽는 설명이며 결과로 출력되지 않습니다.
# 이 파일은 설명과 실행 코드를 함께 읽는 학습용 Python 파일입니다.
# # 뒤의 내용은 주석입니다. 실행되지 않으며 편집기에 따라 색이 다릅니다.
# 저장: course/concepts/C02_01_normal.py · UTF-8
# · .py.txt가 아닌 .py
# 실행: course 폴더의 터미널에서 python -X utf8
# concepts/C02_01_normal.py
# 터미널 명령과 예상 출력은 이 파일에 붙여 넣지 않습니다.
# 괄호 ()는 함수에 전달할 값을 묶습니다. 따옴표는 문자열의 범위를 나타냅니다.
# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
# [구성요소]
# print: 화면 출력 기능의 이름입니다. print(...)처럼 호출합니다.
# 따옴표: 글자는 작은따옴표 또는 큰따옴표로 둘러쌉니다. 숫자 자체는 따옴표 없이
# 쓸 수 있습니다.
# ,: 여러 값을 함수에 전달할 때 구분합니다. print는 기본적으로 사이에
# 공백을 넣습니다.
# #: 이 기호 뒤부터 그 줄 끝까지는 설명입니다. 따옴표 안의 #는 글자입니다.
# [실행 과정]
# print("온도:", 22.5)는 글자와 숫자를 각각 받아 공백을 사이에
# 넣습니다. print()는 내용 없는 줄 하나를 출력합니다.
# [직접 확장할 문제]
# 이름, 관심 직무, 배우고 싶은 내용을 세 줄로 출력하세요. 설명 주석 한 줄도
# 작성하세요.
# ---------------------------------------------------------------------
# 글자를 출력하려면 따옴표로 감쌉니다.
print("안녕하세요")
# 숫자를 그대로 주면 계산 가능한 숫자 값입니다.
print(100)
# 빈 괄호는 화면에서 줄 하나를 비웁니다.
print()
print("다음 줄")
