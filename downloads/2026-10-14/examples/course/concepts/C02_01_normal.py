# 무엇을 배우나요? print는 값을 화면에 보여 주는 함수입니다. 주석은 사람이 읽는 설명이며 결과로 출력되지 않습니다.
# 이 파일은 설명과 실행 코드를 함께 읽는 학습용 Python 파일입니다.
# # 뒤의 내용은 주석입니다. 실행되지 않으며 편집기에 따라 색이 다릅니다.
# 저장: course/concepts/C02_01_normal.py · UTF-8 · .py.txt가 아닌 .py
# 실행: course 폴더의 터미널에서 python -X utf8 concepts/C02_01_normal.py
# 터미널 명령과 예상 출력은 이 파일에 붙여 넣지 않습니다.
# 괄호 ()는 함수에 전달할 값을 묶습니다. 따옴표는 문자열의 범위를 나타냅니다.
# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
# 글자를 출력하려면 따옴표로 감쌉니다.
print("안녕하세요")
# 숫자를 그대로 주면 계산 가능한 숫자 값입니다.
print(100)
# 빈 괄호는 화면에서 줄 하나를 비웁니다.
print()
print("다음 줄")
