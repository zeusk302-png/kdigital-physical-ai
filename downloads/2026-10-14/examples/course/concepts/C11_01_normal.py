# 무엇을 배우나요? 반복문은 같은 동작을 여러 값에 수행합니다. for는 자료에서 값을 하나씩 꺼내 반복 변수에 연결합니다.
# 이 파일은 설명과 실행 코드를 함께 읽는 학습용 Python 파일입니다.
# # 뒤의 내용은 주석입니다. 실행되지 않으며 편집기에 따라 색이 다릅니다.
# 저장: course/concepts/C11_01_normal.py · UTF-8 · .py.txt가 아닌 .py
# 실행: course 폴더의 터미널에서 python -X utf8 concepts/C11_01_normal.py
# 터미널 명령과 예상 출력은 이 파일에 붙여 넣지 않습니다.
# 괄호 ()는 함수에 전달할 값을 묶습니다. 따옴표는 문자열의 범위를 나타냅니다.
# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
scores = [90, 25, 67, 45, 80]
for score in scores:
    # score는 리스트 전체가 아니라 이번에 꺼낸 숫자 하나입니다.
    if score >= 60:
        print(score, "합격")
    else:
        print(score, "불합격")
print("판정 끝")            # 들여쓰기가 없으므로 반복 종료 후 한 번 실행합니다.
