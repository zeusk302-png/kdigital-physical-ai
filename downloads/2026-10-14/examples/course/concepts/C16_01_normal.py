# ---------------------------------------------------------------------
# [구성요소]
# def 이름(매개변수):: 함수를 정의합니다. 매개변수는 들어올 값에 붙인
# 이름입니다.
# 호출: 함수 이름 뒤 괄호에 실제 값을 넣습니다. f_to_c(72)가 호출입니다.
# return: 함수 실행을 끝내고 값을 돌려줍니다. 호출 결과를 변수에
# 저장하거나 계산에 사용할 수 있습니다.
# print와 return: print는 화면에 보여 줍니다. 반환하지 않으면
# 함수의 결과는 None입니다. None은 0과 다릅니다.
# [실행 과정]
# f_to_c(72) 호출 → f에 72 → 계산 → return으로 22.22…
# → result에 저장 → 표시합니다.
# [직접 확장할 문제]
# 가격과 수량을 받아 금액을 반환하는 함수를 만드세요. 함수 안 출력 대신 호출한
# 쪽에서 출력하세요.
# ---------------------------------------------------------------------
def f_to_c(f):
    """화씨 숫자를 받아 섭씨 숫자를 돌려줍니다."""
    # 첫 문자열은 함수 설명인 docstring입니다.
    return (f - 32) * 5 / 9

result = f_to_c(72)
print(f"변환 결과: {result:.1f}")
print(f"어는점: {f_to_c(32):.1f}")
# 같은 처리 절차를 값만 바꿔 여러 번 사용합니다.
