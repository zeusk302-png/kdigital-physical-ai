# 무엇을 배우나요? 함수는 이름을 붙인 처리 절차입니다. 정의만 하면 실행되지 않고 호출할 때 실행됩니다. return은 결과를 호출한 곳에 돌려줍니다.
# 이 파일은 설명과 실행 코드를 함께 읽는 학습용 Python 파일입니다.
# # 뒤의 내용은 주석입니다. 실행되지 않으며 편집기에 따라 색이 다릅니다.
# 저장: course/concepts/C16_01_normal.py · UTF-8 · .py.txt가 아닌 .py
# 실행: course 폴더의 터미널에서 python -X utf8 concepts/C16_01_normal.py
# 터미널 명령과 예상 출력은 이 파일에 붙여 넣지 않습니다.
# 괄호 ()는 함수에 전달할 값을 묶습니다. 따옴표는 문자열의 범위를 나타냅니다.
# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
def f_to_c(f):
    """화씨 숫자를 받아 섭씨 숫자를 돌려줍니다."""
    # 첫 문자열은 함수 설명인 docstring입니다.
    return (f - 32) * 5 / 9

result = f_to_c(72)
print(f"변환 결과: {result:.1f}")
print(f"어는점: {f_to_c(32):.1f}")
# 같은 처리 절차를 값만 바꿔 여러 번 사용합니다.
