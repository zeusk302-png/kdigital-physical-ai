# 터미널 명령과 예상 출력은 이 파일에 붙여 넣지 않습니다.
# 괄호 ()는 함수에 전달할 값을 묶습니다. 따옴표는 문자열의 범위를 나타냅니다.
# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
# 따옴표가 없는 name은 변수 이름이고 "홍길동"은 문자열 값입니다.
name = "홍길동"
age = 25
temperature = 22.5
active = True
print("이름:", name)
print("나이:", age)
print("온도:", temperature)
print("작동:", active)
# print("name")과 print(name)의 결과를 비교해 보세요.
