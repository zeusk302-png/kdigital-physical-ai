# 괄호 ()는 함수에 전달할 값을 묶습니다. 따옴표는 문자열의 범위를 나타냅니다.
# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
# [구성요소]
# 변수 이름: 역할이 드러나는 이름을 씁니다. 숫자로 시작할 수 없고 대소문자를
# 구별합니다.
# =: 오른쪽 값을 먼저 구합니다. 그다음 왼쪽 변수의 현재 값이 바뀝니다.
# 재대입: 같은 이름에 새 값을 연결할 수 있습니다. stock = stock +
# 2는 현재 stock에 2를 더합니다.
# 독립된 값: 숫자를 다른 변수에 대입한 후 원래 이름을 바꿔도 이전 숫자가 함께
# 바뀌지는 않습니다.
# [실행 과정]
# stock이 10 → 입고 후 15 → 출고 후 12로 변합니다. 각 대입 직후
# 출력하면 변화가 보입니다.
# [직접 확장할 문제]
# 잔액 20000원에서 3500원을 두 번 지출하는 코드를 작성하세요. 각 지출
# 직후 잔액을 출력하세요.
# ---------------------------------------------------------------------
# 따옴표가 없는 name은 변수 이름이고 "홍길동"은 문자열 값입니다.
name = "홍길동"
age = 25
temperature = 22.5
active = True
print("이름:", name)
print("나이:", age)
print("온도:", temperature)
print("작동:", active)
# print("name")과 print(name)의 결과를 비교해 보세요.
