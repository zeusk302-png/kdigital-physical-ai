# ---------------------------------------------------------------------
# [구성요소]
# while 조건:: 본문 실행 전에 매번 조건을 다시 확인합니다.
# 값 갱신: 반복이 끝나도록 재고·횟수 등이 바뀌어야 합니다. 무한 반복은
# 터미널에서 Ctrl+C로 중지합니다.
# break: 가장 가까운 반복문을 즉시 끝냅니다.
# continue: 이번 반복의 남은 부분을 건너뛰고 다음 조건 검사로 돌아갑니다.
# [실행 과정]
# 재고 3에서 한 번 판매할 때마다 1씩 줄이면 3 → 2 → 1 → 0입니다.
# 0에서 조건이 거짓이 되어 종료됩니다.
# [직접 확장할 문제]
# 잔액 1000원에서 300원씩 구매하고 잔액이 부족하면 끝내세요. 마지막 잔액을
# 출력하세요.
# ---------------------------------------------------------------------
while True:
    command = input("명령(start/skip/done): ").strip().lower()
    if command == "done":
        break                  # 반복을 완전히 끝냅니다.
    if command == "skip":
        continue               # 이번 처리와 출력을 건너뜁니다.
    print("처리:", command)
print("종료")
