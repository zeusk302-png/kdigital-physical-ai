# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
# [구성요소]
# try:: 실패할 수 있는 변환을 시도하는 코드 묶음입니다.
# except ValueError:: 숫자로 바꿀 수 없는 값 같은 해당 예외만
# 처리합니다.
# 입력 오류와 범위 오류: 문자를 숫자로 변환하는 실패와 숫자가 허용 범위 밖인
# 문제는 다른 검사입니다.
# Traceback: 마지막 줄에서 오류 종류를 읽고 파일명과 줄 번호로 원인
# 위치를 확인합니다.
# [실행 과정]
# abc 입력 → int 변환 실패 → except에서 안내 → continue로
# 다시 입력합니다. -1은 변환 성공 후 범위 검사에서 거절합니다.
# [직접 확장할 문제]
# 300원 자판기에 잘못된 글자나 음수를 넣으면 다시 묻고, 300원 이상이면
# 거스름돈을 출력하세요.
# ---------------------------------------------------------------------
while True:
    raw = input("수량(0 이상 정수): ")
    try:
        quantity = int(raw)
    except TypeError:
        print("정수로 입력하세요.")
        continue
    # 여기부터는 quantity가 정수로 바뀐 상태입니다.
    if quantity < 0:
        print("0 이상이어야 합니다.")
        continue
    break
print("확정 수량:", quantity)
# 잘못된 입력은 재고나 금액을 바꾸는 계산 전에 검사합니다.
