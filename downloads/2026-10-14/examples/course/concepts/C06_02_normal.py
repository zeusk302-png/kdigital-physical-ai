# 무엇을 배우나요? input은 입력을 기다렸다가 문자열로 돌려줍니다. 숫자 계산을 하려면 필요한 종류로 바꿔야 합니다.
# 이 파일은 설명과 실행 코드를 함께 읽는 학습용 Python 파일입니다.
# # 뒤의 내용은 주석입니다. 실행되지 않으며 편집기에 따라 색이 다릅니다.
# 저장: course/concepts/C06_02_normal.py · UTF-8 · .py.txt가 아닌 .py
