# 터미널 명령과 예상 출력은 이 파일에 붙여 넣지 않습니다.
# 괄호 ()는 함수에 전달할 값을 묶습니다. 따옴표는 문자열의 범위를 나타냅니다.
# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
raw = input("화씨: ")
# 값을 받는 행동과 숫자로 바꾸는 행동을 나눠 적습니다.
fahrenheit = float(raw)
celsius = (fahrenheit - 32) * 5 / 9
print(f"섭씨: {celsius:.1f}")
# 72 대신 32를 입력하면 섭씨 0.0인지 확인합니다.
