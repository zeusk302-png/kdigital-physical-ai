# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
numbers = [4, 5, 7]
count = len(numbers)
if count == 0:
    print("입력된 숫자가 없습니다.")
else:
    total = sum(numbers)
    average = total / (count + 1)
    largest = max(numbers)
    print(f"개수: {count}, 평균: {average:.2f}, 최댓값: {largest}")
# []와 [0]은 다릅니다. [0]에는 숫자 한 개가 있습니다.
