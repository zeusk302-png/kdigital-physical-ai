# 무엇을 배우나요? while은 조건이 참인 동안 반복합니다. for처럼 정해진 자료를 읽는 대신 종료 조건과 값 변화가 중요합니다.
# 이 파일은 설명과 실행 코드를 함께 읽는 학습용 Python 파일입니다.
# # 뒤의 내용은 주석입니다. 실행되지 않으며 편집기에 따라 색이 다릅니다.
# 저장: course/concepts/C14_02_normal.py · UTF-8 · .py.txt가 아닌 .py
# 실행: course 폴더의 터미널에서 python -X utf8 concepts/C14_02_normal.py
# 터미널 명령과 예상 출력은 이 파일에 붙여 넣지 않습니다.
# 괄호 ()는 함수에 전달할 값을 묶습니다. 따옴표는 문자열의 범위를 나타냅니다.
# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
while True:
    command = input("명령(start/skip/done): ").strip()
    if command == "done":
        break                  # 반복을 완전히 끝냅니다.
    if command == "skip":
        continue               # 이번 처리와 출력을 건너뜁니다.
    print("처리:", command)
print("종료")
