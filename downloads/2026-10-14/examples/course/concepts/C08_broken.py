# ---------------------------------------------------------------------
# [구성요소]
# == / !=: 같은지·다른지 비교합니다. =는 대입이며 비교와 다릅니다.
# > >= < <=: 초과·이상·미만·이하입니다. 기준값과 같은 값의 포함 여부가
# 다릅니다.
# and / or: and는 두 조건 모두 참, or는 하나 이상 참이면 참입니다.
# not: 참·거짓을 반대로 만듭니다. True는 따옴표 없는 bool 값입니다.
# [실행 과정]
# 28 > 28은 False이고 28 >= 28은 True입니다. 괄호로 각각의
# 비교를 묶어 논리 판단을 읽습니다.
# [직접 확장할 문제]
# 잔액과 재고를 바꿔 주문 가능 여부를 비교하세요. 10·30·31의 범위 판단을
# 각각 출력하세요.
# ---------------------------------------------------------------------
stock = 3
balance = 5000
price = 2000
# 재고가 있고 돈도 충분해야 주문할 수 있습니다.
can_order = (stock > 0) and (balance >= price)
print("주문 가능:", can_order)
temperature = 35
outside = (temperature < 10) and (temperature > 30)
print("범위 밖:", outside)
print("범위 안:", not outside)
