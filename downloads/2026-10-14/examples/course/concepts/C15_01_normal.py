# ---------------------------------------------------------------------
raw = input("정수: ")
try:
    number = int(raw)
except ValueError:
    print("정수로 바꿀 수 없습니다.")
else:
    # else는 try가 예외 없이 끝났을 때 실행합니다.
    print("입력한 수:", number)
