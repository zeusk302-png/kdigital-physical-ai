# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
# [구성요소]
# strip(): 양끝 공백을 제거합니다. 중간 공백을 모두 지우는 기능은 아닙니다.
# lower(): 영문 대문자를 소문자로 바꿉니다. 결과는 새 문자열이므로 사용할
# 변수에 저장합니다.
# replace(old, new): 지정한 글자를 다른 글자로 바꿉니다. 빈
# 문자열로 바꾸면 해당 글자를 제거합니다.
# 순서: 정리 → 숫자 변환 → 계산 순서입니다. 숫자로 바꿀 수 없는 글자는
# 예외 단원에서 처리합니다.
# [실행 과정]
# "  START  " → strip 후 "START" → lower 후
# "start"입니다. 처음부터 한 줄로 묶지 않고 단계별 값을 확인합니다.
# [직접 확장할 문제]
# " 8,500원 "을 8500으로 바꾸는 과정을 단계별 변수로 적고 10% 할인
# 금액을 출력하세요.
# ---------------------------------------------------------------------
raw = "  START  "
# 양끝 공백이 보이도록 출력에서 대괄호를 둘러줍니다.
print(f"원본: [{raw}]")
trimmed = raw.strip()
print(f"공백 제거: [{trimmed}]")
command = trimmed.lower()
print(f"소문자: [{command}]")
