# 무엇을 배우나요? 예외는 실행 중 계속 진행할 수 없는 상황입니다. 예상한 입력 변환 실패를 처리하면 안내 후 다시 입력받을 수 있습니다.
# 이 파일은 설명과 실행 코드를 함께 읽는 학습용 Python 파일입니다.
# # 뒤의 내용은 주석입니다. 실행되지 않으며 편집기에 따라 색이 다릅니다.
# 저장: course/concepts/C15_02_normal.py · UTF-8 · .py.txt가 아닌 .py
# 실행: course 폴더의 터미널에서 python -X utf8 concepts/C15_02_normal.py
# 터미널 명령과 예상 출력은 이 파일에 붙여 넣지 않습니다.
# 괄호 ()는 함수에 전달할 값을 묶습니다. 따옴표는 문자열의 범위를 나타냅니다.
# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
while True:
    raw = input("수량(0 이상 정수): ")
    try:
        quantity = int(raw)
    # TODO: int 변환 실패에서 실제 발생하는 ValueError를 처리하세요.
    except TypeError:
        print("정수로 입력하세요.")
        continue
    # 여기부터는 quantity가 정수로 바뀐 상태입니다.
    if quantity < 0:
        print("0 이상이어야 합니다.")
        continue
    break
print("확정 수량:", quantity)
