# 무엇을 배우나요? 변수는 값에 붙이는 이름입니다. =는 같다는 비교가 아니라 오른쪽 결과를 계산해 왼쪽 이름에 연결하는 대입입니다.
# 이 파일은 설명과 실행 코드를 함께 읽는 학습용 Python 파일입니다.
# # 뒤의 내용은 주석입니다. 실행되지 않으며 편집기에 따라 색이 다릅니다.
# 저장: course/concepts/C04_02_normal.py · UTF-8 · .py.txt가 아닌 .py
# 실행: course 폴더의 터미널에서 python -X utf8 concepts/C04_02_normal.py
# 터미널 명령과 예상 출력은 이 파일에 붙여 넣지 않습니다.
# 괄호 ()는 함수에 전달할 값을 묶습니다. 따옴표는 문자열의 범위를 나타냅니다.
# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
stock = 10                 # 시작 재고입니다.
original = stock           # 지금 숫자 10을 다른 이름에도 연결합니다.
print("시작:", stock)
stock = stock + 5          # 오른쪽 10 + 5를 계산한 뒤 stock에 저장합니다.
print("입고 후:", stock)
stock = stock - 3          # 현재 값 15에서 3을 뺍니다.
print("출고 후:", stock)
print("처음 기록:", original)
