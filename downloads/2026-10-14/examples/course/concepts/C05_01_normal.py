# 괄호 ()는 함수에 전달할 값을 묶습니다. 따옴표는 문자열의 범위를 나타냅니다.
# 코드는 위에서 아래로 실행됩니다. 먼저 결과를 예상한 뒤 실행하세요.
# ---------------------------------------------------------------------
sensor = "S01"
print("길이:", len(sensor))
print("첫 글자:", sensor[0])
print("앞 두 글자:", sensor[0:2])
# 문자열 +는 두 글자를 이어 붙입니다.
print("장치-" + sensor)
