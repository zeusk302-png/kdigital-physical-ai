# [구성요소]
# int / float: int는 정수, float는 소수 부분이 있는 수 등을
# 표현합니다. 3.0도 float입니다.
# str / bool: str은 문자열, bool은 True 또는
# False입니다. True와 "True"는 다릅니다.
# + - * /: 덧셈·뺄셈·곱셈·나눗셈입니다. 여기서 정수의 / 결과도
# float입니다.
# // % **: //는 내림 나눗셈, %는 나머지, **는 거듭제곱입니다.
# float를 쓰면 // 결과도 float일 수 있습니다.
# [실행 과정]
# 125 // 60은 2, 125 % 60은 5입니다. (72 - 32) * 5
# / 9는 괄호 속 뺄셈을 먼저 수행합니다.
# [직접 확장할 문제]
# 367초를 분과 초로 나누세요. 100도 화씨의 섭씨값도 계산하고 계산 순서를
# 말로 설명하세요.
# ---------------------------------------------------------------------
# type의 결과에서 int, float, str, bool이라는 종류 이름을 읽습니다.
print(type(25))
print(type(3.0))
print(type("25"))
print(type(True))
# 숫자 +는 덧셈이지만 문자열 +는 연결입니다.
print(3 + 5)
print("3" + "5")
print(10 / 2)      # 나누어떨어져도 float인 5.0입니다.
print(10.0 // 3)   # 피연산자에 float가 있으므로 결과는 3.0입니다.
print(2 ** 3)      # 2를 세 번 곱합니다.
