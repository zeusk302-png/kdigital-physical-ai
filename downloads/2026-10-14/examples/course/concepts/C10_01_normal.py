# ---------------------------------------------------------------------
temperatures = [22, 24, 20]
print("처음:", temperatures)
print("첫 값:", temperatures[0])
temperatures[1] = 25       # 두 번째 위치의 값을 수정합니다.
temperatures.append(26)   # 끝에 새 값을 추가합니다.
print("변경 후:", temperatures)
print("개수:", len(temperatures))
