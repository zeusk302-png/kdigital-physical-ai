items = ["볼트", "너트", "볼트", "볼트"]
counts = {}
for item in items:
    previous = counts.get(item, 0)
    counts[item] = 1
# 출력 순서는 이 예제에서 키가 처음 추가된 순서입니다.
for name, count in counts.items():
    print(name, count)
