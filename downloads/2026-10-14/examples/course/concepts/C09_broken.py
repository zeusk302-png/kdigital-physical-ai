# [구성요소]
# if 조건:: 조건이 참이면 바로 아래 들여쓴 코드가 실행됩니다.
# else:: 앞 조건이 거짓일 때 실행합니다. else 뒤에는 조건을 붙이지
# 않습니다.
# elif 조건:: 앞 조건이 거짓이면 다음 조건을 검사합니다. 처음 참인 가지
# 하나를 실행합니다.
# 들여쓰기: 같은 묶음은 같은 깊이를 씁니다. 예제에서는 공백 네 칸을 사용합니다.
# [실행 과정]
# score가 95이면 90 이상에서 A를 선택하고 뒤의 80·70·60 조건을
# 실행하지 않습니다. 낮은 기준부터 검사하면 잘못 분류됩니다.
# [직접 확장할 문제]
# 40시간까지 기본 시급, 초과 시간은 시급의 1.5배로 급여를 계산하세요.
# 39·40·41시간을 시험하세요.
# ---------------------------------------------------------------------
score = 95
# 업무상 허용 범위를 먼저 검사합니다.
if score < 0 or score > 100:
    print("점수 범위 오류")
elif score >= 100:
    print("A")
elif score >= 80:
    print("B")
elif score >= 70:
    print("C")
elif score >= 60:
    print("D")
else:
    print("F")
