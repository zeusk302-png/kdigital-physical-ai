# [구성요소]
# 입력 규칙: 숫자를 한 줄씩 입력하고 done으로 끝냅니다. 잘못된 숫자는
# 안내하고 다음 입력을 받습니다.
# 저장과 처리: 숫자를 리스트에 모으고 합계·개수·평균·최댓값을 계산합니다.
# 빈 자료: 바로 done이면 계산할 값이 없습니다. 평균과 max를 호출하기
# 전에 확인합니다.
# 시험: 정상 입력·잘못된 입력·숫자 0·바로 종료를 각각 시험합니다. 한 예제
# 출력만 맞는 것으로 끝내지 않습니다.
# [실행 과정]
# 4 → [4], 5 → [4, 5], bad → 변경 없음, 7 → [4, 5,
# 7], done → 종료. 숫자 개수는 3이고 평균은 5.33입니다.
# [직접 확장할 문제]
# 완성 코드를 가리고 숫자 입력·종료·오류 안내·요약을 직접 작성하세요.
# 4/5/bad/7/done과 done만 입력하는 경우를 시험하세요.
# ---------------------------------------------------------------------
def get_int(prompt):
    """정수로 변환 가능한 입력을 받을 때까지 다시 묻습니다."""
    while True:
        raw = input(prompt)
        try:
            number = int(raw)
        except ValueError:
            print("정수로 입력하세요.")
            continue
        return number         # 함수가 끝나므로 while도 함께 끝납니다.

quantity = get_int("수량: ")
print("받은 값:", quantity)
# 이 함수는 음수도 정수로 받습니다. 업무 범위 검사는 호출한 쪽에 추가합니다.
