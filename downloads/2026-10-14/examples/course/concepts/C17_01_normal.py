def get_int(prompt):
    """정수로 변환 가능한 입력을 받을 때까지 다시 묻습니다."""
    while True:
        raw = input(prompt)
        try:
            number = int(raw)
        except ValueError:
            print("정수로 입력하세요.")
            continue
        return number         # 함수가 끝나므로 while도 함께 끝납니다.

quantity = get_int("수량: ")
print("받은 값:", quantity)
# 이 함수는 음수도 정수로 받습니다. 업무 범위 검사는 호출한 쪽에 추가합니다.
