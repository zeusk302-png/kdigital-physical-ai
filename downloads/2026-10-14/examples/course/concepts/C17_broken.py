def average(numbers):
    """숫자 목록의 평균을 반환합니다. 빈 목록은 None을 반환합니다."""
    if len(numbers) == 0:
        return None
    return sum(numbers) / len(numbers)

numbers = []
while True:
    raw = input("숫자(done 종료): ")
