def show_double(number):
    # 화면에 출력하지만 호출한 곳으로 숫자를 돌려주지는 않습니다.
    print(number * 2)

def calculate_double(number):
    # 숫자를 반환합니다. 화면 출력은 호출한 쪽에서 정합니다.
    return number * 2

shown = show_double(3)
calculated = calculate_double(3)
print("출력 함수 결과:", shown)
print("반환 함수 결과:", calculated)
print("반환값에 1 더하기:", calculated + 1)
